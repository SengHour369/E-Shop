ALTER TABLE checkout_reservations ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE checkout_reservations ADD COLUMN IF NOT EXISTS guest_session_id uuid;
ALTER TABLE checkout_reservations DROP CONSTRAINT IF EXISTS ck_reservation_owner;
ALTER TABLE checkout_reservations ADD CONSTRAINT ck_reservation_owner CHECK ((user_id IS NOT NULL) <> (guest_session_id IS NOT NULL));
ALTER TABLE promotion_usages ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE promotion_usages ADD COLUMN IF NOT EXISTS guest_session_id uuid;
ALTER TABLE promotion_usages DROP CONSTRAINT IF EXISTS ck_promotion_usage_owner;
ALTER TABLE promotion_usages ADD CONSTRAINT ck_promotion_usage_owner CHECK ((user_id IS NOT NULL) <> (guest_session_id IS NOT NULL));
CREATE TABLE IF NOT EXISTS product_reviews (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id bigint NOT NULL REFERENCES products(id),
 guest_session_id uuid, user_id bigint, author varchar(80) NOT NULL,
 rating integer NOT NULL CHECK(rating BETWEEN 1 AND 5), title varchar(120) NOT NULL, body varchar(2000) NOT NULL,
 moderation_status varchar(255) NOT NULL DEFAULT 'PENDING' CHECK(moderation_status IN ('PENDING','APPROVED','REJECTED')),
 verified_purchase boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now(),
 moderated_by bigint, moderated_at timestamptz, version bigint NOT NULL DEFAULT 0,
 CHECK ((user_id IS NOT NULL) <> (guest_session_id IS NOT NULL)),
 UNIQUE(product_id,guest_session_id), UNIQUE(product_id,user_id)
);
CREATE INDEX IF NOT EXISTS ix_review_public ON product_reviews(product_id,moderation_status,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_review_moderation ON product_reviews(moderation_status,id);
